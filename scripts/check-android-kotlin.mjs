#!/usr/bin/env node
// 本机 Gradle 跑不了任何真实 task（Windows 上的 AF_UNIX/NIO 全局故障，见
// docs/PROJECT.md 与历次任务日志），于是 Kotlin 改动连"编不编得过"都验不了——
// 这一直是 Android 侧最大的盲区：改完只能靠读，错字要等 CI 才暴露。
//
// 这个脚本绕开 Gradle：用 Gradle 缓存里已经下好的 kotlin-compiler-embeddable
// 在当前进程直接编译 :app 的 main 源集，classpath 由本机 Android SDK 的 android.jar
// 加缓存里的 jar / aar(classes.jar) 拼出来。它**不是** Gradle 门禁的替代品——
// 不跑 KSP、不做资源合并、不生成 R 类、不跑 lint 与单元测试——但能在本机拦下
// 语法错误、未解析引用、类型不匹配这三类最常见的失误。
//
// 编完还会用 JUnit 直接跑一遍 JVM 单测（--no-tests 可跳过）。
//
// 并发安全（T10.176，2026-09-25）：本脚本可能被多个 worktree 同时调用（heavy.mjs
// 允许 3 个并发槽）。编译产物——生成的 R/BuildConfig 桩、.class 输出、给 kotlinc/java
// 用的 argfile——此前固定写在 os.tmpdir()/tokenledger-android-kotlin，多个进程同时跑
// 会互相 rmSync/覆盖对方的产物：轻则 ClassNotFoundException，重则用另一棵 worktree
// 编出的 .class 跑测试却报「通过」。现在这部分产物用 fs.mkdtempSync 生成的每次运行
// 专属目录，退出（含信号中断）时只清理自己那份，不影响其他并发进程。aar 解压缓存
// 按内容命名（stamp + 文件名），继续跨进程共享以省重复解压。
// 已知限制：清理只挂在正常退出与 SIGINT/SIGTERM/SIGHUP/SIGBREAK 上；SIGKILL、Windows
// 强制结束进程（taskkill /F、任务管理器）与宿主崩溃都不会触发，会在 os.tmpdir() 下
// 留下 tokenledger-android-kotlin-run-* 目录，需要人工删除（不影响之后的运行）。
//
// aar 缓存的原子写入（P2-1，独立评审 20260925-0608 指出，2026-09-25 追加修复）：
// 共享缓存意味着多个进程可能在冷缓存时同时判定"这个 aar 还没解过"，同时开始解压。
// 此前直接用 .NET ExtractToFile 写最终文件名，两个进程的写入会互相踩踏——不会读到
// 半份文件（FileShare.None 会让后来者直接报共享冲突），但落败的一方会把这个 aar
// 记成"解压失败"而在当次运行的 classpath 里整个消失，表现为一次假性编译失败
// （比如少了 Compose 的类，报"未解析引用"，需要重跑而非真实回归）。现在改成：
// 先解压到同目录、带进程号 + 随机后缀的临时文件，成功后 fs.renameSync 到最终文件名；
// rename 前如果发现最终文件名已经被别的进程写好，直接丢弃自己这份临时文件，不覆盖、
// 不重试。同一个卷内的 rename 是原子操作，读取方（下面的 fast-path existsSync 判断、
// 以及最终拼 classpath）永远只看得到"完全不存在"或"完全写好"两种状态之一。
//
// 用法：node scripts/check-android-kotlin.mjs [--verbose] [--no-tests]
// 退出码：0 通过；1 编译报错或测试失败；2 环境不满足（缺 SDK / 缺缓存 jar）。

import { execFileSync, spawnSync } from 'node:child_process';
import crypto from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import process from 'node:process';

const HOME = os.homedir();
const GRADLE_MODULES = path.join(HOME, '.gradle', 'caches', 'modules-2', 'files-2.1');
const SOURCE_ROOT = path.join('apps', 'android', 'app', 'src', 'main', 'java');
// 单测源集一起编：它们此前完全没有本机验证手段，签名漂移要等 CI 才暴露。
// 依赖只有 junit4 / org.json / coroutines-test，都在同一份 Gradle 缓存里。
// debug 源集必须一起编：预览夹具（ledgerSnapshotFixture 等）定义在那里，
// 单测直接引用它们——Gradle 的 testDebugUnitTest 也是这么组的。
const TEST_SOURCE_ROOTS = [
  path.join('apps', 'android', 'app', 'src', 'debug', 'java'),
  path.join('apps', 'android', 'app', 'src', 'test', 'java'),
];
const R_STUB_MARKER = '// generated by check-android-kotlin.mjs';

/**
 * 找能用的 java：JAVA_HOME 优先，其次 Homebrew 的 openjdk（与 run-android-gradle.mjs 同序），
 * 最后退回 PATH 上的 java。macOS 的 /usr/bin/java 只是系统桩，没装 JDK 时一跑就报
 * "Unable to locate a Java Runtime"，所以只有在探测不到 JDK 时才用它。
 */
function resolveJava() {
  const exe = process.platform === 'win32' ? 'java.exe' : 'java';
  const homes = [
    process.env.JAVA_HOME,
    '/opt/homebrew/opt/openjdk@17',
    '/opt/homebrew/opt/openjdk',
    '/usr/local/opt/openjdk@17',
    '/usr/local/opt/openjdk',
  ].filter(Boolean);
  for (const home of homes) {
    const candidate = path.join(home, 'bin', exe);
    if (!fs.existsSync(candidate)) continue;
    // 产物是 JVM 17 字节码，JUnit 也用同一个 java 跑；更老的 JDK 会报
    // UnsupportedClassVersionError，跳过它继续找。读不到版本时当作可用。
    const major = javaMajorVersion(home);
    if (major !== undefined && major < 17) continue;
    return candidate;
  }
  return 'java';
}

/** 读 JDK 根目录 `release` 文件里的 JAVA_VERSION 主版本号；读不到返回 undefined。 */
function javaMajorVersion(home) {
  try {
    const release = fs.readFileSync(path.join(home, 'release'), 'utf8');
    const match = /^JAVA_VERSION="?(?:1\.)?(\d+)/mu.exec(release);
    return match ? Number(match[1]) : undefined;
  } catch {
    return undefined;
  }
}
const JAVA = resolveJava();

/** android.jar：优先 compileSdk，退而求其次用本机最高的 platform。 */
function findAndroidJar(compileSdk) {
  const roots = [
    process.env.ANDROID_HOME,
    process.env.ANDROID_SDK_ROOT,
    path.join(HOME, 'AppData', 'Local', 'Android', 'Sdk'),
    path.join(HOME, 'Android', 'Sdk'),
    path.join(HOME, 'Library', 'Android', 'sdk'),
  ].filter(Boolean);
  for (const root of roots) {
    const platforms = path.join(root, 'platforms');
    if (!fs.existsSync(platforms)) continue;
    const preferred = path.join(platforms, `android-${compileSdk}`, 'android.jar');
    if (fs.existsSync(preferred)) return preferred;
    const available = fs.readdirSync(platforms)
      .filter((name) => name.startsWith('android-'))
      .sort((a, b) => Number(b.slice(8)) - Number(a.slice(8)));
    for (const name of available) {
      const jar = path.join(platforms, name, 'android.jar');
      if (fs.existsSync(jar)) return jar;
    }
  }
  return null;
}

function readCompileSdk() {
  const buildFile = path.join('apps', 'android', 'app', 'build.gradle.kts');
  const match = fs.readFileSync(buildFile, 'utf8').match(/compileSdk\s*=\s*(\d+)/u);
  return match ? match[1] : '36';
}

/**
 * argfile 里反斜杠是转义符（kotlinc 与 java 都是），Windows 路径直接写进去会被吞掉。
 * 统一换成正斜杠再加引号——JVM 在 Windows 上认正斜杠。
 */
function quoteForArgFile(value) {
  return '"' + String(value).split('\\').join('/') + '"';
}

function walk(dir, predicate, out = []) {
  if (!fs.existsSync(dir)) return out;
  for (const name of fs.readdirSync(dir)) {
    const entry = path.join(dir, name);
    const stat = fs.statSync(entry);
    if (stat.isDirectory()) walk(entry, predicate, out);
    else if (predicate(entry)) out.push(entry);
  }
  return out;
}

/**
 * 把 aar 里的 classes.jar 解到 dest；aar 里没有 classes.jar 时什么都不写。
 * Windows 用 PowerShell 的 .NET ZipFile，macOS/Linux 用系统自带的 unzip。
 */
function extractClassesJar(aar, dest) {
  if (process.platform === 'win32') {
    // Windows PowerShell 5.1 里 [System.IO.Compression.ZipFile] 不是默认加载的，
    // 少了 Add-Type 会静默失败——之前就是这样解出 0 个 jar，classpath 里没有
    // Compose，编译器把整份 UI 报成"未解析引用"。
    execFileSync('powershell', [
      '-NoProfile', '-Command',
      `$ErrorActionPreference='Stop';` +
      `Add-Type -AssemblyName System.IO.Compression.FileSystem;` +
      `$zip=[System.IO.Compression.ZipFile]::OpenRead('${aar.replace(/'/gu, "''")}');` +
      `$entry=$zip.GetEntry('classes.jar');` +
      `if($entry){[System.IO.Compression.ZipFileExtensions]::ExtractToFile($entry,'${dest.replace(/'/gu, "''")}',$true)};` +
      `$zip.Dispose()`,
    ], { stdio: 'ignore' });
    return;
  }
  // unzip -p 把条目写到 stdout；退出码 11 表示 aar 里没有这个条目（纯资源包）。
  const run = spawnSync('unzip', ['-p', aar, 'classes.jar'], { maxBuffer: 1024 * 1024 * 1024 });
  if (run.error) throw run.error;
  if (run.status === 11) return;
  if (run.status !== 0) throw new Error(`unzip 退出码 ${run.status}：${String(run.stderr).trim()}`);
  fs.writeFileSync(dest, run.stdout);
}

/**
 * aar 是 zip，编译只需要里面的 classes.jar；解出来缓存到临时目录复用。
 *
 * 原子写入保证（P2-1，见文件头注释）：先解压到 `${target}.tmp-<pid>-<随机>`，
 * 成功后 rename 到 `target`；rename 前如果 `target` 已存在（别的并发进程刚写完），
 * 丢弃自己这份临时文件，不覆盖。`target` 只可能处于"不存在"或"已经由某次成功的
 * rename 完整写好"这两种状态之一，不会有第三种半写状态——`jars`/调用方看到的
 * 永远是一份完整、可用的 jar。
 */
function extractAarClasses(aarFiles, cacheDir) {
  fs.mkdirSync(cacheDir, { recursive: true });
  const jars = [];
  const failures = [];
  for (const aar of aarFiles) {
    const stamp = path.basename(path.dirname(aar));
    const target = path.join(cacheDir, `${stamp}-${path.basename(aar, '.aar')}.jar`);
    if (!fs.existsSync(target)) {
      const tmpTarget = `${target}.tmp-${process.pid}-${crypto.randomBytes(4).toString('hex')}`;
      try {
        // 解压目标是临时文件名，不是最终的 target——见上方 P2-1 说明。
        extractClassesJar(aar, tmpTarget);
        // aar 里没有 classes.jar（纯资源包）：tmpTarget 从未被创建，
        // 什么都不用做——target 也不会存在，下面的 existsSync 会自然跳过它，
        // 与改动前的行为一致（不计入 failures）。
        if (fs.existsSync(tmpTarget)) {
          if (fs.existsSync(target)) {
            // 别的并发进程已经解出同一个文件了：丢弃自己这份，不覆盖、不重复计数。
            fs.rmSync(tmpTarget, { force: true });
          } else {
            try {
              fs.renameSync(tmpTarget, target);
            } catch (renameErr) {
              // 极小概率：existsSync 检查之后、renameSync 之前，被别的进程抢先
              // rename 到了同一个 target。输的一方丢弃自己这份；如果目标依然
              // 不存在，说明是真的 IO 错误，继续抛出。
              if (fs.existsSync(target)) {
                fs.rmSync(tmpTarget, { force: true });
              } else {
                throw renameErr;
              }
            }
          }
        }
      } catch {
        fs.rmSync(tmpTarget, { force: true });
        failures.push(path.basename(aar));
        continue;
      }
    }
    if (fs.existsSync(target)) jars.push(target);
  }
  if (jars.length === 0) {
    console.error(
      `无法从 ${aarFiles.length} 个 aar 里解出 classes.jar，classpath 会缺掉 Compose 与 androidx，\n` +
      '编译结果没有意义。本次检查作废。',
    );
    process.exit(2);
  }
  if (failures.length > 0) {
    console.warn(`解压失败 ${failures.length} 个 aar（已跳过）：${failures.slice(0, 5).join('、')}`);
  }
  return jars;
}

function findCompilerJars() {
  const pick = (group, artifact) => {
    const base = path.join(GRADLE_MODULES, group, artifact);
    if (!fs.existsSync(base)) return null;
    for (const version of fs.readdirSync(base).sort().reverse()) {
      for (const hash of fs.readdirSync(path.join(base, version))) {
        const dir = path.join(base, version, hash);
        if (!fs.statSync(dir).isDirectory()) continue;
        const jar = fs.readdirSync(dir)
          .find((name) => name.endsWith('.jar') && !name.includes('-sources'));
        if (jar) return path.join(dir, jar);
      }
    }
    return null;
  };
  return {
    compiler: pick('org.jetbrains.kotlin', 'kotlin-compiler-embeddable'),
    stdlib: pick('org.jetbrains.kotlin', 'kotlin-stdlib'),
    annotations: pick('org.jetbrains', 'annotations'),
    coroutines: pick('org.jetbrains.kotlinx', 'kotlinx-coroutines-core-jvm'),
    composePlugin: pick('org.jetbrains.kotlin', 'kotlin-compose-compiler-plugin-embeddable'),
  };
}

/**
 * R / BuildConfig 由 AGP 在构建时生成，本地没有。给一份最小桩：
 * 只声明源码里真正引用到的成员，缺了会以未解析引用暴露出来，不会静默放过。
 */
function writeGeneratedStubs(stubDir) {
  fs.mkdirSync(stubDir, { recursive: true });
  const sources = [
    ...walk(SOURCE_ROOT, (entry) => entry.endsWith('.kt')),
    ...TEST_SOURCE_ROOTS.flatMap((root) => walk(root, (entry) => entry.endsWith('.kt'))),
  ].map((file) => fs.readFileSync(file, 'utf8')).join('\n');
  // 资源类别不写死：源码里出现哪几种 R.<类别>.<名字> 就生成哪几种。
  // 写死的话，新引用一种资源（比如 R.font）会以"未解析引用"的形式报成假错误。
  const byType = new Map();
  for (const match of sources.matchAll(/\bR\.([a-z]\w*)\.(\w+)/gu)) {
    if (!byType.has(match[1])) byType.set(match[1], new Set());
    byType.get(match[1]).add(match[2]);
  }
  const block = (name, entries) => `    object ${name} {\n${
    entries.map((id) => `        const val ${id}: Int = 0`).join('\n')
  }\n    }`;

  const pkg = 'com.jeidorf.tokenledger.mobile';
  fs.writeFileSync(path.join(stubDir, 'GeneratedStubs.kt'), [
    R_STUB_MARKER,
    `package ${pkg}`,
    '',
    'internal object R {',
    ...[...byType.keys()].sort().map((type) => block(type, [...byType.get(type)].sort())),
    '}',
    '',
    'internal object BuildConfig {',
    '    const val DEBUG: Boolean = true',
    '    const val VERSION_NAME: String = "0.0.0"',
    '    const val VERSION_CODE: Int = 0',
    '    const val APPLICATION_ID: String = "com.jeidorf.tokenledger.mobile"',
    ...readBuildConfigFields().map(({ name, type }) => {
      const value = type === 'String' ? '""' : type === 'Boolean' ? 'false' : '0.0';
      return `    const val ${name}: ${type} = ${value}`;
    }),
    '}',
    '',
  ].join('\n'), 'utf8');
}

/**
 * 自定义 buildConfigField 从 build.gradle.kts 里读，别在这里硬编码：
 * 以后加字段忘了同步，这里会静默给出"未解析引用"的假错误。
 */
function readBuildConfigFields() {
  const buildFile = path.join('apps', 'android', 'app', 'build.gradle.kts');
  const source = fs.readFileSync(buildFile, 'utf8');
  const pattern = /buildConfigField\s*\(\s*"(\w+)"\s*,\s*"(\w+)"/gu;
  const kotlinType = { String: 'String', double: 'Double', float: 'Float', int: 'Int', long: 'Long', boolean: 'Boolean' };
  const fields = [];
  for (const match of source.matchAll(pattern)) {
    fields.push({ name: match[2], type: kotlinType[match[1]] ?? 'String' });
  }
  return fields;
}

function main() {
  const verbose = process.argv.includes('--verbose');
  const compileSdk = readCompileSdk();
  const androidJar = findAndroidJar(compileSdk);
  const jars = findCompilerJars();

  if (!androidJar) {
    console.error(
      `找不到 android.jar（compileSdk ${compileSdk}）。这台机器没装 Android SDK 时跳过本检查，\n` +
      'Android 编译以 CI 或有 SDK 的机器为准。',
    );
    process.exit(2);
  }
  if (!jars.compiler || !jars.stdlib || !jars.composePlugin) {
    console.error(
      '找不到 kotlin-compiler-embeddable / kotlin-stdlib / compose 编译器插件。\n' +
      '本检查复用 Gradle 缓存里已下好的 jar，缓存为空时跳过。',
    );
    process.exit(2);
  }
  // 退回 PATH 的 java 没经过 release 文件的版本筛选，这里按 `java -version` 的输出再卡一次 17。
  const javaProbe = spawnSync(JAVA, ['-version'], { encoding: 'utf8' });
  const probeVersion = /version "(?:1\.)?(\d+)/u.exec(`${javaProbe.stderr ?? ''}${javaProbe.stdout ?? ''}`);
  const probeMajor = probeVersion ? Number(probeVersion[1]) : undefined;
  if (javaProbe.error || javaProbe.status !== 0 || (probeMajor !== undefined && probeMajor < 17)) {
    console.error(
      `找不到可用的 Java 17+ 运行时（${JAVA}${probeMajor !== undefined ? `，版本 ${probeMajor}` : ''}）。` +
      '请安装 JDK 17（如 brew install openjdk@17）或把 JAVA_HOME 指到 17 及以上的 JDK。',
    );
    process.exit(2);
  }

  // aar 解压缓存内容按来源命名（stamp + 文件名），是只读追加的纯缓存，可以安全跨
  // 进程共享，省得每次运行都重新解压几百个 aar。真正不能共享的是本次编译的产物——
  // 生成的桩、.class 输出与 argfile 用 mkdtempSync 各自独立，见文件头「并发安全」。
  const aarCache = path.join(os.tmpdir(), 'tokenledger-android-kotlin', 'aar-classes');
  fs.mkdirSync(aarCache, { recursive: true });
  const runDir = fs.mkdtempSync(path.join(os.tmpdir(), 'tokenledger-android-kotlin-run-'));
  let runDirCleaned = false;
  const cleanupRunDir = () => {
    if (runDirCleaned) return;
    runDirCleaned = true;
    try {
      fs.rmSync(runDir, { recursive: true, force: true });
    } catch {
      // 尽力而为：清理失败不影响本次检查已经得出的结果
    }
  };
  process.on('exit', cleanupRunDir);
  for (const signal of ['SIGINT', 'SIGTERM', 'SIGHUP', 'SIGBREAK']) {
    process.on(signal, () => {
      cleanupRunDir();
      process.exit(130);
    });
  }
  if (verbose) console.log(`本次运行独占目录：${runDir}`);

  const stubDir = path.join(runDir, 'stubs');
  const outDir = path.join(runDir, 'out');
  fs.mkdirSync(outDir, { recursive: true });

  const cacheJars = walk(
    GRADLE_MODULES,
    (entry) => entry.endsWith('.jar') && !entry.includes('-sources'),
  );
  const aarJars = extractAarClasses(
    walk(GRADLE_MODULES, (entry) => entry.endsWith('.aar')),
    aarCache,
  );
  writeGeneratedStubs(stubDir);

  const compileClasspath = [androidJar, ...cacheJars, ...aarJars].join(path.delimiter);
  const launcherClasspath = [
    jars.compiler, jars.stdlib, jars.annotations, jars.coroutines,
  ].filter(Boolean).join(path.delimiter);

  const mainSources = walk(SOURCE_ROOT, (entry) => entry.endsWith('.kt'));
  const testSources = TEST_SOURCE_ROOTS.flatMap((root) => walk(root, (entry) => entry.endsWith('.kt')));
  const sources = [
    ...mainSources,
    ...testSources,
    ...walk(stubDir, (entry) => entry.endsWith('.kt')),
  ];

  // 200+ 个 jar 拼出来的 classpath 有几万字符，直接当命令行参数会超过 Windows 的
  // 32k 上限，进程根本起不来（表现为退出码非 0 但两条流都是空的）。argfile 里
  // 除了源文件也可以放选项，把 -cp 一并搬进去。
  const argFile = path.join(runDir, 'args.txt');
  const quote = (value) => `"${String(value).replace(/\\/gu, '/')}"`;
  fs.writeFileSync(
    argFile,
    [
      '-cp',
      quote(compileClasspath),
      ...sources.map((file) => quote(path.resolve(file))),
    ].join('\n'),
    'utf8',
  );

  // 编译器把诊断写在 stderr，成功时 execFileSync 只回 stdout，会把错误整段吞掉；
  // spawnSync 无论退出码都同时给两条流。
  const run = spawnSync(JAVA, [
    '-Xmx4g',
    '-cp', launcherClasspath,
    'org.jetbrains.kotlin.cli.jvm.K2JVMCompiler',
    '-no-stdlib',
    '-nowarn',
    '-jvm-target', '17',
    '-Xplugin=' + jars.composePlugin,
    '-d', outDir,
    `@${argFile}`,
  ], { encoding: 'utf8', maxBuffer: 256 * 1024 * 1024 });
  const output = `${run.stdout ?? ''}\n${run.stderr ?? ''}`;
  const failed = run.status !== 0;
  if (run.error) {
    console.error(`无法启动 Kotlin 编译器：${run.error.message}`);
    process.exit(2);
  }

  if (/^exception:/mu.test(output) || /NoClassDefFoundError/u.test(output)) {
    console.error('Kotlin 编译器未能启动，本次检查无效（不要当作通过）：');
    console.error(output.split(/\r?\n/u).slice(0, 8).join('\n'));
    process.exit(2);
  }

  const errors = output.split(/\r?\n/u).filter((line) => /error:/u.test(line));
  console.log(
    `Android Kotlin 离线编译：main ${mainSources.length} + test ${testSources.length} 个源文件` +
    `（另含 R/BuildConfig 桩），compileSdk ${compileSdk}，错误 ${errors.length} 条。`,
  );
  if (verbose && output.trim()) console.log(output);

  if (errors.length > 0) {
    console.error('\n编译错误：');
    for (const line of errors.slice(0, 60)) console.error(`  ${line}`);
    if (errors.length > 60) console.error(`  …另有 ${errors.length - 60} 条`);
    console.error(
      '\n注意：本检查不跑 KSP、不合并资源、不生成真实 R 类，因此少数错误可能来自桩而非源码；\n' +
      '但语法错误、未解析引用与类型不匹配都是真的。',
    );
    process.exit(1);
  }
  if (failed) {
    console.error('编译器退出码非 0 但没有解析出 error 行，请用 --verbose 查看原始输出。');
    process.exit(1);
  }
  console.log('通过：main 与 test 源集均可编译（不含 KSP / 资源合并 / lint）。');

  if (process.argv.includes('--no-tests')) return;
  runUnitTests({ outDir, compileClasspath, testSources, verbose });
}

/**
 * 测试源文件相对 TEST_SOURCE_ROOTS 的目录结构就是它的包名（Kotlin/Java 惯例）。
 * 子包（coordinator/、widget/ 等）的类文件实际编译到 outDir/.../mobile/coordinator/…；
 * 此前这里一律拼根包 com.jeidorf.tokenledger.mobile，子包测试的 existsSync 永远落空，
 * 于是被静默漏判成"不存在"——45 个测试类只跑了根包的 40 个（T10.172 评审 P2-11）。
 */
function resolveTestClass(file, outDir) {
  for (const root of TEST_SOURCE_ROOTS) {
    const rel = path.relative(root, file);
    if (rel.startsWith('..') || path.isAbsolute(rel)) continue;
    const parts = rel.split(path.sep);
    const simpleName = path.basename(parts[parts.length - 1], '.kt');
    const packageParts = parts.slice(0, -1);
    return {
      name: simpleName,
      fqcn: [...packageParts, simpleName].join('.'),
      classFile: path.join(outDir, ...packageParts, `${simpleName}.class`),
    };
  }
  return null;
}

/**
 * 跑 JVM 单测。Gradle 的 testDebugUnitTest 用 unit-tests.jar 把 android.jar 的方法体
 * 换成"返回默认值"，这里没有那一层，直接用 android.jar：碰到 Android 框架类的桩会抛
 * `RuntimeException: Stub!`。所以结果分三类——通过、真失败、以及**要真机/Robolectric
 * 才能跑的**（Stub!）。第三类单列，不算通过也不算失败，不要拿它当绿灯。
 */
function runUnitTests({ outDir, compileClasspath, testSources, verbose }) {
  const androidJar = compileClasspath.split(path.delimiter)[0];
  const classes = testSources
    .filter((file) => /Test\.kt$/u.test(file))
    .map((file) => resolveTestClass(file, outDir))
    .filter((info) => info && fs.existsSync(info.classFile))
    .sort((a, b) => a.name.localeCompare(b.name));
  if (classes.length === 0) {
    console.warn('没有找到可执行的测试类，跳过。');
    return;
  }

  // 与编译同一个坑：几百个 jar 拼出来的 -cp 超过 Windows 的 32k 参数上限，
  // java 根本起不来，两条流都是空的。用 JDK 9+ 的 @argfile 绕开。
  // android.jar 放最末尾：它里面的 org.json / android.util 都是抛 Stub! 的桩，
  // 排在真 jar 前面会把本来能跑的测试变成"需要真机"。
  const runtimeJars = compileClasspath.split(path.delimiter);
  // build.gradle.kts 把 test 源集的 resources 指到仓库根的 fixtures/：
  // 少了它，读契约夹具的测试会以「Missing shared dashboard fixture」失败，
  // 那是环境缺件，不是被测代码有问题。
  const resourceRoots = [
    path.join('apps', 'android', 'app', 'src', 'test', 'resources'),
    'fixtures',
  ].filter((dir) => fs.existsSync(dir)).map((dir) => path.resolve(dir));
  // build.gradle.kts 里声明的 testImplementation 必须排在这堆缓存 jar 前面：
  // 缓存里还躺着 layoutlib（截图测试的依赖），它自带一份 Android 的 org.json，
  // 会把声明的 org.json:json 顶掉，于是解析行为与 Gradle 下不一致——测试报的红
  // 是 classpath 污染，不是被测代码。
  const declaredTestJars = runtimeJars.filter(
    (jar) => /^(junit|hamcrest-core|json|kotlinx-coroutines-test)-[\d.]/u.test(path.basename(jar)),
  );
  const rest = runtimeJars.slice(1).filter((jar) => !declaredTestJars.includes(jar));
  const runtimeClasspath = [outDir, ...resourceRoots, ...declaredTestJars, ...rest, runtimeJars[0]]
    .join(path.delimiter);
  const runArgFile = path.join(path.dirname(outDir), 'run-args.txt');
  fs.writeFileSync(runArgFile, `-cp ${quoteForArgFile(runtimeClasspath)}\n`, 'utf8');

  const passed = [];
  const failed = [];
  const needsDevice = [];
  for (const info of classes) {
    const run = spawnSync(JAVA, [
      `@${runArgFile}`,
      'org.junit.runner.JUnitCore', info.fqcn,
    ], {
      encoding: 'utf8',
      maxBuffer: 64 * 1024 * 1024,
      // Gradle 跑单测时的工作目录是模块根，有测试用 ../../../fixtures 这样的相对路径读夹具。
      cwd: path.join('apps', 'android', 'app'),
    });
    const output = `${run.stdout ?? ''}${run.stderr ?? ''}`;
    if (run.status === 0) { passed.push(info.name); continue; }
    if (/RuntimeException: Stub!|android\.util\.Log|NoClassDefFoundError: android/u.test(output)) {
      needsDevice.push(info.name);
      continue;
    }
    failed.push({ name: info.name, output });
  }

  console.log(
    `Android JVM 单测：${passed.length} 个测试类通过、${failed.length} 个失败、` +
    `${needsDevice.length} 个需要 Android 运行时（本机以 android.jar 桩运行，见函数注释）。`,
  );
  if (needsDevice.length > 0) console.log(`  需真机/Robolectric：${needsDevice.join('、')}`);
  if (verbose) console.log(`  通过：${passed.join('、')}`);
  if (failed.length > 0) {
    for (const item of failed) {
      console.error(`\n${item.name} 失败：`);
      console.error(item.output.split(/\r?\n/u).filter((line) => line.trim()).slice(0, 24).map((l) => `  ${l}`).join('\n'));
    }
    process.exit(1);
  }
}

main();
