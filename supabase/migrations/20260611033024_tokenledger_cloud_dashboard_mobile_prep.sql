-- outside the RLS boundary so the RLS-wrapped paths will still require
-- per-user filtering, but it lets the anon/admin dashboard views (e.g. the
-- global heatmap on the marketing site, if any) hit a small index.
create index if not exists token_logs_date_idx
  on public.token_logs (public.immutable_date_parse(timestamp));

