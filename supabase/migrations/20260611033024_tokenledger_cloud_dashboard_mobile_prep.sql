-- ============================================================================
-- 6) Deferred refresh pipeline.
-- ============================================================================
-- sync_state is a single-row table that records whether the materialized
-- views are stale. Triggers increment dirty_generation on every
-- INSERT/UPDATE; request_refresh() refreshes the views and marks the
-- generation it actually covered. If new writes arrive while a refresh is
-- running, dirty_generation remains ahead of refreshed_generation so the
-- next refresh cannot accidentally be skipped.
-- ============================================================================

create table if not exists public.sync_state (
  id integer primary key default 1,
  is_dirty boolean not null default true,
  dirty_generation bigint not null default 1,
  refreshed_generation bigint not null default 0,
  last_refreshed_at timestamptz,
  constraint sync_state_single_row check (id = 1)
);

insert into public.sync_state (id, is_dirty, dirty_generation, refreshed_generation, last_refreshed_at)
values (1, true, 1, 0, null)
on conflict (id) do nothing;

alter table public.sync_state
  add column if not exists is_dirty boolean not null default true,
  add column if not exists dirty_generation bigint not null default 1,
  add column if not exists refreshed_generation bigint not null default 0,
  add column if not exists last_refreshed_at timestamptz;

update public.sync_state
   set dirty_generation = case
         when is_dirty and dirty_generation <= refreshed_generation
           then refreshed_generation + 1
         else dirty_generation
       end
 where id = 1;

update public.sync_state
   set is_dirty = dirty_generation > refreshed_generation
 where id = 1;

alter table public.sync_state enable row level security;

drop policy if exists "sync_state_select_own" on public.sync_state;
create policy "sync_state_select_own"
  on public.sync_state
  for select
  to authenticated
  using (true);

