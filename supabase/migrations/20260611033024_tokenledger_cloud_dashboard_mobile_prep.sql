-- TokenLedger Supabase schema (v2)
-- Migration target from SUPABASE_SETUP.sql: adds aggregation materialized views,
-- a single RPC get_dashboard_stats that powers the dashboard, and a deferred
-- refresh pipeline. Run this in the Supabase SQL Editor (see supabase/README.md
-- for the step-by-step playbook).
--
-- Performance goal: replace the "select * from token_logs + client-side
-- aggregation" pattern with a single server-side aggregation that returns
-- StatsData-shaped JSON. With a 100k row corpus this should bring the cloud
-- dashboard response from ~8s to ~0.5s once the materialized views are
-- warmed up.

create extension if not exists pgcrypto;

create or replace function public.immutable_date_parse(val text)
returns date
language plpgsql immutable
set search_path = ''
as $$
begin
  if val !~ '^\d{4}-\d{2}-\d{2}' then
    return null;
  end if;
  return pg_catalog.make_date(
    pg_catalog.substr(val, 1, 4)::integer,
    pg_catalog.substr(val, 6, 2)::integer,
    pg_catalog.substr(val, 9, 2)::integer
  );
exception when others then
  return null;
end;
$$;

