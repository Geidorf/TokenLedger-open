-- ============================================================================
-- 7b) get_yesterday_stats: server-side aggregate for the wallpaper renderer.
-- ============================================================================
-- The desktop/lockscreen wallpaper needs yesterday's totals to draw the
-- day-over-day comparison curve and the % badge. get_dashboard_stats only
-- returns the current range ("today" has no yesterday slot), so the wallpaper
-- path used to pull raw token_logs over REST and re-aggregate client side.
-- That hit the PostgREST 1000-row cap and silently truncated busy days.
--
-- This RPC aggregates yesterday entirely on the server and returns a single
-- jsonb row, so the result is correct regardless of how many rows yesterday
-- had. Shape: { total, requests, hourly: int[24] }. The machine filter mirrors
-- get_dashboard_stats: null / '' / 'all_cloud' aggregates across machines.
create or replace function public.get_yesterday_stats(
  p_user uuid,
  p_machine text default null,
  p_timezone text default 'UTC'
)
returns jsonb
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $$
declare
  v_machine_filter boolean := p_machine is not null
                              and p_machine <> ''
                              and p_machine <> 'all_cloud';
  v_timezone text := coalesce(nullif(p_timezone, ''), 'UTC');
  v_now timestamp;
  v_start date;
  v_end date;
  v_result jsonb;
begin
  if auth.uid() is null or auth.uid() <> p_user then
    raise exception 'get_yesterday_stats: user mismatch (auth.uid()=%, p_user=%)',
      auth.uid(), p_user
      using errcode = '42501';
  end if;

  begin
    v_now := now() at time zone v_timezone;
  exception when others then
    v_timezone := 'UTC';
    v_now := now() at time zone v_timezone;
  end;
  v_end := v_now::date;
  v_start := v_end - 1;

  with rows as (
    select
      t.tool as tool,
      t.input_tokens as input_tokens,
      t.output_tokens as output_tokens,
      t.cached_tokens as cached_tokens,
      t.requests as requests,
      (substr(t.timestamp, 12, 2))::int as hour
    from public.token_logs t
    where t.user_id = p_user
      and (public.immutable_date_parse(t.timestamp)) >= v_start
      and (public.immutable_date_parse(t.timestamp)) < v_end
      and (not v_machine_filter or t.machine_id = p_machine)
  ),
  scored as (
    select
      case when lower(tool) = 'codex'
           then input_tokens + output_tokens
           else input_tokens + output_tokens + cached_tokens
      end as tokens,
      requests,
      hour
    from rows
  ),
  hourly as (
    select hour, sum(tokens)::bigint as tokens
    from scored
    where hour >= 0 and hour < 24
    group by hour
  )
  select jsonb_build_object(
    'total', coalesce((select sum(tokens) from scored), 0)::bigint,
    'requests', coalesce((select sum(requests) from scored), 0)::bigint,
    'hourly', (
      select coalesce(
        jsonb_agg(coalesce(h.tokens, 0) order by g.h),
        '[]'::jsonb
      )
      from generate_series(0, 23) as g(h)
      left join hourly h on h.hour = g.h
    )
  ) into v_result;

  return v_result;
end;
$$;

revoke execute on function public.get_yesterday_stats(uuid, text, text) from public, anon;
grant execute on function public.get_yesterday_stats(uuid, text, text) to authenticated, service_role;

-- ============================================================================
-- 8) First-time priming.
-- ============================================================================
-- On a fresh install the materialized views are empty until request_refresh
-- is called. The first caller would otherwise see a blank dashboard. We
-- prime the views at the end of the migration so the dashboard works
-- immediately. If the table is empty this is a no-op; on a 100k-row corpus
-- it can take a few seconds.
do $$
begin
  perform public.refresh_token_logs_summaries();
  update public.sync_state
     set is_dirty = false,
         refreshed_generation = dirty_generation,
         last_refreshed_at = now()
   where id = 1;
exception when others then
  -- Don't fail the migration if the first refresh hiccups; the dashboard
  -- can still recover by calling request_refresh() later.
  raise notice 'Initial refresh skipped: %', sqlerrm;
end;
$$;
